Future<void> generatEEGReport(RxList<BrainScoreModel> scores) async {
  // print(scores.value.score);
  //Create a PDF document.
  final sf.PdfDocument document = sf.PdfDocument();
  //Add page to the PDF
  final sf.PdfPage page = document.pages.add();
  //Get page client size
  final Size pageSize = page.getClientSize();
  //Draw rectangle
  page.graphics.drawRectangle(
      bounds: Rect.fromLTWH(0, 0, pageSize.width, pageSize.height),
      pen: sf.PdfPen(sf.PdfColor(142, 170, 219)));
  //Generate PDF grid.
  final sf.PdfGrid grid = getGrid(scores);
  //Draw the header section by creating text element
  final sf.PdfLayoutResult result = drawHeader(page, pageSize, grid, scores);
  //Draw grid
  drawGrid(page, grid, result);
  //Add invoice footer
  drawFooter(page, pageSize);
  //Save the PDF document
  final List<int> bytes = document.saveSync();
  //Dispose the document.
  document.dispose();
  //Save and launch the file.
  final loginDetails = GetStorage().read('loginDetails');
  final userName = loginDetails?['user']?['firstName'] != null &&
          loginDetails?['user']?['lastName'] != null
      ? '${loginDetails['user']['firstName']} ${loginDetails['user']['lastName']}'
      : loginDetails?['user']?['name'] ?? 'User';

  await saveAndLaunchFile(
      bytes, '${userName}_${DateTime.now().microsecondsSinceEpoch}.pdf');
}

//Draws the invoice header
sf.PdfLayoutResult drawHeader(sf.PdfPage page, Size pageSize, sf.PdfGrid grid, RxList<BrainScoreModel> scores) {
  //Draw rectangle
  page.graphics.drawRectangle(
      brush: sf.PdfSolidBrush(sf.PdfColor(91, 126, 215)),
      bounds: Rect.fromLTWH(0, 0, pageSize.width - 0, 90));
  //Draw string
  final loginDetails = GetStorage().read('loginDetails');
  final userName = loginDetails?['user']?['firstName'] != null &&
          loginDetails?['user']?['lastName'] != null
      ? '${loginDetails['user']['firstName']} ${loginDetails['user']['lastName']}'
      : loginDetails?['user']?['name'] ?? 'User';

  page.graphics.drawString('EEG Brain Signal Report for $userName',
      sf.PdfStandardFont(sf.PdfFontFamily.helvetica, 28),
      brush: sf.PdfBrushes.white,
      bounds: Rect.fromLTWH(25, 0, pageSize.width - 115, 90),
      format:
          sf.PdfStringFormat(lineAlignment: sf.PdfVerticalAlignment.middle));

  final sf.PdfFont contentFont =
      sf.PdfStandardFont(sf.PdfFontFamily.helvetica, 10);
  final Size contentSize = contentFont.measureString('');
  final userEmail = loginDetails?['user']?['email'] ?? 'Not provided';
  String address = 'Patient Name: $userName\r\n'
      'Email: $userEmail\r\n\r\n'
      'Report Generated: ${DateFormat('MMMM dd, yyyy - hh:mm a').format(DateTime.now())}';

  return sf.PdfTextElement(text: address, font: contentFont).draw(
      page: page,
      bounds: Rect.fromLTWH(30, 120, pageSize.width - (contentSize.width + 30),
          pageSize.height))!;
}

//Draws the grid
void drawGrid(sf.PdfPage page, sf.PdfGrid grid, sf.PdfLayoutResult result) {
  Rect? totalPriceCellBounds;
  Rect? quantityCellBounds;
  grid.beginCellLayout = (Object sender, sf.PdfGridBeginCellLayoutArgs args) {
    final sf.PdfGrid grid = sender as sf.PdfGrid;
    if (args.cellIndex == grid.columns.count - 1) {
      totalPriceCellBounds = args.bounds;
    } else if (args.cellIndex == grid.columns.count - 2) {
      quantityCellBounds = args.bounds;
    }
  };
  result = grid.draw(
      page: page, bounds: Rect.fromLTWH(0, result.bounds.bottom + 40, 0, 0))!;
}

void drawFooter(sf.PdfPage page, Size pageSize) {
  final sf.PdfPen linePen =
      sf.PdfPen(sf.PdfColor(142, 170, 219), dashStyle: sf.PdfDashStyle.custom);
  linePen.dashPattern = <double>[3, 3];
  
  // Add footer text
  page.graphics.drawString(
    'This report is generated by ADDvEEG Medical System - Confidential Medical Document',
    sf.PdfStandardFont(sf.PdfFontFamily.helvetica, 8),
    brush: sf.PdfBrushes.gray,
    bounds: Rect.fromLTWH(30, pageSize.height - 30, pageSize.width - 60, 20),
    format: sf.PdfStringFormat(alignment: sf.PdfTextAlignment.center)
  );
}

//Create PDF grid and return
sf.PdfGrid getGrid(RxList<BrainScoreModel> brainScores) {
  print('GetGrid Called');
  final sf.PdfGrid grid = sf.PdfGrid();
  grid.columns.add(count: 4);

  final sf.PdfGridRow headerRow = grid.headers.add(1)[0];

  headerRow.style.backgroundBrush = sf.PdfSolidBrush(sf.PdfColor(68, 114, 196));
  headerRow.style.textBrush = sf.PdfBrushes.white;
  headerRow.cells[0].value = 'Serial Number';
  headerRow.cells[0].stringFormat.alignment = sf.PdfTextAlignment.center;
  headerRow.cells[1].value = 'Date & Time';
  headerRow.cells[2].value = 'Device Id';
  headerRow.cells[3].value = 'Score';
  // quiz.value.score
  //     .map((e) => addQuizItem(e.data.questionare.type.toString(), e.createdAt,
  //         e.data.questions.length, e.score, grid))
  //     .toList();
  for (int i = 0; i < brainScores.length; i++) {
    addBrainScores(i + 1, brainScores[i].createdAt!, brainScores[i].deviceId!,
        brainScores[i].score!, grid);
  }
  grid.applyBuiltInStyle(sf.PdfGridBuiltInStyle.listTable4Accent5);

  grid.columns[1].width = 200;
  for (int i = 0; i < headerRow.cells.count; i++) {
    headerRow.cells[i].style.cellPadding =
        sf.PdfPaddings(bottom: 5, left: 5, right: 5, top: 5);
  }
  for (int i = 0; i < grid.rows.count; i++) {
    final sf.PdfGridRow row = grid.rows[i];
    for (int j = 0; j < row.cells.count; j++) {
      final sf.PdfGridCell cell = row.cells[j];
      if (j == 0) {
        cell.stringFormat.alignment = sf.PdfTextAlignment.center;
      }
      cell.style.cellPadding =
          sf.PdfPaddings(bottom: 5, left: 5, right: 5, top: 5);
    }
  }
  return grid;
}

//Create and row for the grid.
void addBrainScores(int SerialNo, DateTime dateTime, String deviceId,
    String score, sf.PdfGrid grid) {
  print('addQuizItem Called');
  final sf.PdfGridRow row = grid.rows.add();
  row.cells[0].value = SerialNo.toString();
  final DateFormat format = DateFormat.yMMMMd('en_US').add_Hm();
  row.cells[1].value = format.format(dateTime);
  row.cells[2].value = deviceId.toString();
  row.cells[3].value = score.toString();
}
